/// What a US layout's `SDL_GetKeyName(SDL_GetKeyFromScancode(scancode))` gives as one code point.
pub fn us_layout_char(scancode: i32) -> Option<char> {
    Some(match scancode {
        4..=29 => (b'A' + (scancode - 4) as u8) as char,
        30..=38 => (b'1' + (scancode - 30) as u8) as char,
        39 => '0',
        45 => '-',
        46 => '=',
        47 => '[',
        48 => ']',
        49 => '\\',
        51 => ';',
        52 => '\'',
        53 => '`',
        54 => ',',
        55 => '.',
        56 => '/',
        _ => return None,
    })
}
