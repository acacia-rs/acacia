/// Whether `query` answers `value` to every part of `key` (`a&b`).
pub fn matches(key: &str, value: i32, query: &dyn Fn(&str) -> crate::entity::molang::Value) -> bool {
    key.split('&').all(|part| query(part).num() as i32 == value)
}
