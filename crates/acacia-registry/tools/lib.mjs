// Shared by gen.mjs and items.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const CACHE = process.argv[2] ?? path.join(HERE, '.cache');
export const GEN = path.join(HERE, '..', 'src', 'generated');
export const HEADER = '// @generated by crates/acacia-registry/tools/gen.mjs. Do not edit.\n';

export const read = (f) => fs.readFileSync(path.join(CACHE, f));
export const fail = (msg) => { throw new Error(msg); };
export const str = (s) => JSON.stringify(s);
export const camel = (s) => s.replace(/^minecraft:/, '').split(/[_:.\s/]+/).filter(Boolean)
  .map((w) => w[0].toUpperCase() + w.slice(1).toLowerCase()).join('');
export const write = (file, text) => { fs.mkdirSync(GEN, { recursive: true }); fs.writeFileSync(path.join(GEN, file), text); };

// Java tags of `kind` (block, item) unzipped from the server jar into tags/, resolved over `names` (in enum order).
// Writes `<kind>_tags.rs`: an enum `typeName` and one bitset per tag over the enum.
export function writeTags(kind, typeName, names) {
  const dir = path.join(CACHE, 'tags', 'data', 'minecraft', 'tags', kind);
  const files = fs.readdirSync(dir, { recursive: true }).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\\/g, '/').slice(0, -5)).sort();
  const known = new Set(names);
  const members = new Map();
  const resolve = (name) => {
    if (members.has(name)) return members.get(name);
    const set = new Set();
    for (const v of JSON.parse(fs.readFileSync(path.join(dir, `${name}.json`), 'utf8')).values) {
      const id = typeof v === 'string' ? v : v.id;
      if (id.startsWith('#')) resolve(id.slice(1).replace('minecraft:', '')).forEach((b) => set.add(b));
      else if (known.has(id)) set.add(id);
      else if (typeof v === 'string' || v.required !== false) fail(`${kind} tag ${name}: unknown ${id}`);
    }
    members.set(name, set);
    return set;
  };
  const words = Math.ceil(names.length / 64);
  const index = new Map(names.map((n, i) => [n, i]));
  let out = `${HEADER}use crate::tag::Tag;\n\n`;
  out += `/// Java 26.3 ${kind} tags, resolved (nested tags expanded).\n`;
  out += `#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n#[repr(u16)]\npub enum ${typeName} {\n`;
  out += files.map((t) => `    ${camel(t)},\n`).join('');
  out += '}\n\n';
  out += `pub(crate) static TAGS: [Tag<${words}>; ${files.length}] = [\n`;
  for (const t of files) {
    const bits = Array.from({ length: words }, () => 0n);
    for (const n of resolve(t)) { const i = index.get(n); bits[i >> 6] |= 1n << BigInt(i & 63); }
    out += `    Tag { name: ${str(`minecraft:${t}`)}, bits: [${bits.map((w) => `0x${w.toString(16)}`).join(', ')}] },\n`;
  }
  out += '];\n';
  write(`${kind}_tags.rs`, out);
  return files.length;
}
