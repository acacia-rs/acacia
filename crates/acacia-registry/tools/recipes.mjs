// Generates src/generated/recipes.rs: Java 26.3's shaped and shapeless crafting recipes, from the server jar's
// data/minecraft/recipe unzipped into <cacheDir>/recipes (README.md "Data sources").
// Usage: node crates/acacia-registry/tools/recipes.mjs <cacheDir>
import fs from 'node:fs';
import path from 'node:path';
import { CACHE, camel, fail, str, write } from './lib.mjs';

const HEADER = '// @generated by crates/acacia-registry/tools/recipes.mjs. Do not edit.\n';
const dir = path.join(CACHE, 'recipes', 'data', 'minecraft', 'recipe');
const item = (id) => `Item::${camel(id)}`;

// An ingredient is an item id, a `#tag`, or a list of item ids.
const choice = (v) => {
  if (Array.isArray(v)) return v.length === 1 ? choice(v[0]) : `Choice::Items(&[${v.map(item).join(', ')}])`;
  if (typeof v !== 'string') fail(`ingredient ${JSON.stringify(v)}`);
  return v.startsWith('#') ? `Choice::Tag(ItemTag::${camel(v.slice(1))})` : `Choice::Item(${item(v)})`;
};

const rows = [];
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const r = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  let shape = 'None';
  let inputs;
  if (r.type === 'minecraft:crafting_shaped') {
    const width = Math.max(...r.pattern.map((p) => p.length));
    shape = `Some((${width}, ${r.pattern.length}))`;
    inputs = r.pattern.flatMap((p) => [...p.padEnd(width)].map((c) => (c === ' ' ? 'Choice::Empty' : choice(r.key[c] ?? fail(`${file}: key ${c}`)))));
  } else if (r.type === 'minecraft:crafting_shapeless') {
    inputs = r.ingredients.map(choice);
  } else {
    continue;
  }
  const id = file.slice(0, -5);
  rows.push(`    CraftingRecipe { id: ${str(id)}, shape: ${shape}, inputs: &[${inputs.join(', ')}], result: ${item(r.result.id)}, count: ${r.result.count ?? 1} },\n`);
}

let out = `${HEADER}use crate::item::Item;\nuse crate::recipe::{Choice, CraftingRecipe};\nuse crate::tag::ItemTag;\n\n`;
out += `/// Java 26.3's shaped and shapeless crafting recipes, by id.\npub(crate) static CRAFTING: &[CraftingRecipe] = &[\n${rows.join('')}];\n`;
write('recipes.rs', out);
console.log(`${rows.length} crafting recipes`);
