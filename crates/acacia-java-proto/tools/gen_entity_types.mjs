// Writes src/entity_types.rs from a 26.3 data-generator report and EntityDump.java's output:
// node tools/gen_entity_types.mjs <reports>/registries.json <entity-dump.json>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const entries = JSON.parse(readFileSync(process.argv[2], 'utf8'))['minecraft:entity_type'].entries;
const names = Object.entries(entries).sort((a, b) => a[1].protocol_id - b[1].protocol_id).map(([name]) => name);
names.forEach((n, i) => { if (entries[n].protocol_id !== i) throw new Error(`gap at ${i}`); });
const dump = JSON.parse(readFileSync(process.argv[3], 'utf8'));
const kinds = { none: 'None', pushable: 'Pushable', solid: 'Solid' };
const float = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const shapes = names.map((n, i) => {
  const d = dump[i];
  if (d?.name !== n || d.id !== i) throw new Error(`dump disagrees at ${i}: ${d?.name} vs ${n}`);
  const baby = d.baby ? `Some((${float(d.baby[0])}, ${float(d.baby[1])}, ${d.babyData}))` : 'None';
  return `    EntityShape { width: ${float(d.width)}, height: ${float(d.height)}, collision: EntityCollision::${kinds[d.collision]}, baby: ${baby} },`;
});
const out = [
  '// Generated by tools/gen_entity_types.mjs from the 26.3 registries.json report and EntityDump. Do not edit.',
  '',
  '/// `minecraft:entity_type` names by registry id.',
  `pub const ENTITY_TYPES: [&str; ${names.length}] = [`,
  ...names.map((n) => `    ${JSON.stringify(n)},`),
  '];',
  '',
  '/// What blocks a moving entity: `Solid` (`canBeCollidedWith`: boats, shulkers) blocks everyone, `Pushable` only vehicles.',
  '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
  'pub enum EntityCollision {',
  '    None,',
  '    Pushable,',
  '    Solid,',
  '}',
  '',
  '/// A type\'s default size, collision and, for types with a synced baby flag, the baby\'s size and that data id.',
  '#[derive(Clone, Copy, Debug, PartialEq)]',
  'pub struct EntityShape {',
  '    pub width: f32,',
  '    pub height: f32,',
  '    pub collision: EntityCollision,',
  '    pub baby: Option<(f32, f32, u8)>,',
  '}',
  '',
  '/// Shapes by registry id.',
  `pub const ENTITY_SHAPES: [EntityShape; ${names.length}] = [`,
  ...shapes,
  '];',
  '',
];
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '../src/entity_types.rs'), out.join('\n'));
