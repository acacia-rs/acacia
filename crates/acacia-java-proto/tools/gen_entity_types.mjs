// Writes src/entity_types.rs from a 26.3 data-generator report: node tools/gen_entity_types.mjs <reports>/registries.json
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const entries = JSON.parse(readFileSync(process.argv[2], 'utf8'))['minecraft:entity_type'].entries;
const names = Object.entries(entries).sort((a, b) => a[1].protocol_id - b[1].protocol_id).map(([name]) => name);
names.forEach((n, i) => { if (entries[n].protocol_id !== i) throw new Error(`gap at ${i}`); });
const out = [
  '// Generated by tools/gen_entity_types.mjs from the 26.3 registries.json report. Do not edit.',
  '',
  '/// `minecraft:entity_type` names by registry id.',
  `pub const ENTITY_TYPES: [&str; ${names.length}] = [`,
  ...names.map((n) => `    ${JSON.stringify(n)},`),
  '];',
  '',
];
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '../src/entity_types.rs'), out.join('\n'));
