// Writes src/ids.rs from a 26.3 data-generator report: node tools/gen_ids.mjs <reports>/packets.json
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const report = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const out = ['// Generated by tools/gen_ids.mjs from the 26.3 packets.json report. Do not edit.', ''];
for (const [state, directions] of Object.entries(report)) {
  out.push(`pub mod ${state} {`);
  for (const [direction, packets] of Object.entries(directions)) {
    out.push(`    pub mod ${direction} {`);
    for (const [name, { protocol_id }] of Object.entries(packets)) {
      const constant = name.replace('minecraft:', '').replace(/[/-]/g, '_').toUpperCase();
      out.push(`        pub const ${constant}: i32 = ${protocol_id};`);
    }
    out.push('    }');
  }
  out.push('}', '');
}
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '../src/ids.rs'), out.join('\n').trimEnd() + '\n');
