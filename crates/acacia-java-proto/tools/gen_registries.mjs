// Writes src/registry/data/*.txt and src/registry/generated.rs from a 26.3 data-generator report:
// node tools/gen_registries.mjs <reports>/registries.json
// One name per line, the line index being the protocol id. Entity types stay in gen_entity_types.mjs.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REGISTRIES = [
  'attribute', 'block_entity_type', 'command_argument_type', 'data_component_type', 'fluid', 'game_event',
  'map_decoration_type', 'menu', 'mob_effect', 'number_format_type', 'particle_type', 'potion', 'sound_event',
  'villager_profession', 'villager_type',
];

const report = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const root = join(dirname(fileURLToPath(import.meta.url)), '../src/registry');
mkdirSync(join(root, 'data'), { recursive: true });

const out = ['// Generated by tools/gen_registries.mjs from the 26.3 registries.json report. Do not edit.', '', 'use super::Registry;', ''];
for (const key of REGISTRIES) {
  const entries = report[`minecraft:${key}`].entries;
  const names = Object.entries(entries).sort((a, b) => a[1].protocol_id - b[1].protocol_id).map(([name]) => name);
  names.forEach((n, i) => { if (entries[n].protocol_id !== i) throw new Error(`${key}: gap at ${i}`); });
  writeFileSync(join(root, 'data', `${key}.txt`), names.join('\n') + '\n');
  out.push(`pub static ${key.toUpperCase()}: Registry = Registry::new("minecraft:${key}", include_str!("data/${key}.txt"));`);
}
out.push('', '/// Every generated registry.', `pub static ALL: [&Registry; ${REGISTRIES.length}] = [${REGISTRIES.map((k) => '&' + k.toUpperCase()).join(', ')}];`, '');
writeFileSync(join(root, 'generated.rs'), out.join('\n'));
